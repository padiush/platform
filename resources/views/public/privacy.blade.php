        <h1 class="text-2xl font-bold pt-4">1. Introducción</h1>
        <p>Bienvenido a Padiush. Nos importa tu privacidad y queremos que sepas exactamente qué sucede con la información que nos proporcionas. Esta Política de Privacidad te explicará cómo recopilamos, usamos, protegemos y gestionamos tus datos.</p>

        <h1 class="text-2xl font-bold pt-4">2. ¿Qué información recopilamos?</h1>
        <p>Cuando te registras y utilizas nuestra plataforma, recopilamos la siguiente información:</p>
        <ul class="list-disc list-inside">
            <li>Información personal: Esto incluye tu nombre y dirección de correo electrónico, que necesitamos para crear tu cuenta y comunicarnos contigo.</li>
            <li>Información de tus investigaciones: Aquí se incluyen los temas y títulos de tus investigaciones, los formularios de entrevista personalizados que creas, y cualquier información relacionada con el uso de especies vegetales. Si decides recopilar información personal de los expertos entrevistados, también almacenaremos esa información.</li>
            <li>Fotografías y dibujos científicos: Si subes imágenes de especies botánicas a la plataforma, también las almacenaremos.</li>
        </ul>
        <p>Aunque almacenamos esta información, tú sigues siendo el propietario de tus datos personales e información de investigación.</p>
        <p>Además, es posible que recopilemos información adicional si nos contactas directamente o si participas en encuestas o promociones.</p>
        
        <h1 class="text-2xl font-bold pt-4">3. Uso de la información</h1>
        <p>Usamos la información que recopilamos para ayudarte a acceder y gestionar tu información y tus investigaciones en la plataforma. Esto incluye permitirte acceder a la información de investigaciones creadas por otros usuarios que te hayan invitado a participar. No utilizaremos tu información para nuestros propios fines sin tu consentimiento.</p>

        <h1 class="text-2xl font-bold pt-4">4. Compartir información</h1>
        <p>Nos tomamos tu privacidad muy en serio. Por eso, no compartiremos tu información con terceros.</p>

        <h1 class="text-2xl font-bold pt-4">5. Almacenamiento y seguridad de la información</h1>
        <p>Tus datos se guardan de manera segura en servidores proporcionados por Amazon Web Services, una empresa líder en servicios de almacenamiento en la nube. Para proteger aún más tus datos, realizamos copias de seguridad diarias que se almacenan de manera segura y se utilizan solo en caso de que necesitemos restaurar la información.</p>
        <p>Si detectamos un acceso no autorizado a tu información, te contactaremos para informarte sobre lo ocurrido y explicarte cómo estamos trabajando para resolver el problema. Nos comprometemos a ser transparentes durante todo el proceso.</p>

        <h1 class="text-2xl font-bold pt-4">6. Derechos del usuario</h1>
        <p>Como usuario de Padiush, tienes varios derechos:</p>
        <ul class="list-disc list-inside">
            <li>Acceso y modificación: Puedes ver y cambiar tu información en cualquier momento a través de la plataforma.</li>
            <li>Eliminación: Si eres el propietario (autor principal) de una investigación, puedes eliminar la información de esa investigación en cualquier momento.</li>
            <li>Exportación: Si eres el autor principal de una investigación, o si el autor principal de una investigación te lo permite a través del formulario respectivo, puedes exportar toda la información de la misma.</li>
            <li>Borrado de cuenta: Puedes borrar tu cuenta (y toda tu información de proyectos de investigación) en cualquier momento. Ten en cuenta que tu información puede permanecer en nuestras copias de seguridad hasta por un máximo de un año.</li>
        </ul>

        <h1 class="text-2xl font-bold pt-4">7. Cookies y tecnologías de seguimiento</h1>
        <p>Para ayudarnos a entender mejor cómo se usa nuestra plataforma y cómo podemos mejorarla, utilizamos Google Analytics. Esta herramienta nos ayuda a analizar el comportamiento de los usuarios, su origen y las tecnologías que utilizan.</p>

        <h1 class="text-2xl font-bold pt-4">8. Cambios a esta política</h1>
        <p>Si decidimos cambiar esta política de privacidad, estamos obligados a hacértelo saber. Te enviaremos un correo electrónico al menos 30 días antes de que los cambios entren en vigor. Así, tendrás tiempo para revisar los cambios antes de que se apliquen.</p>
        <p>Por favor, recuerda que esta política de privacidad puede cambiar de vez en cuando. Te recomendamos que la revises periódicamente para estar al tanto de cualquier cambio.</p>

